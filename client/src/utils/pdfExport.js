// ─── Monthly Summary PDF ──────────────────────────────────────────────────────

/**
 * Export a combined monthly summary (income + expenses + balance).
 * @param {object} summary   - { totalIncome, totalExpenses, balance, recentTransactions }
 * @param {Array}  monthly   - Monthly trend array [{ name, Income, Expenses }]
 * @param {object} user      - { name, email }
 * @param {number} month
 * @param {number} year
 */
export const exportMonthlySummaryPDF = (summary, monthly, user, month, year) => {
  const doc = new jsPDF();
  const monthName = new Date(year, month - 1).toLocaleString('default', { month: 'long' });

  drawHeader(doc, 'Monthly Financial Summary', `${monthName} ${year}`);

  doc.setFontSize(9);
  doc.setTextColor(80, 80, 80);
  doc.text(`User: ${user?.name || 'N/A'}  |  Email: ${user?.email || 'N/A'}`, 14, 40);
  doc.text(`Generated: ${new Date().toLocaleDateString('en-US', { dateStyle: 'long' })}`, 14, 46);

  // KPI summary table
  autoTable(doc, {
    startY: 54,
    head: [['Metric', 'Amount']],
    body: [
      ['Total Income', formatCurrency(summary?.totalIncome || 0)],
      ['Total Expenses', formatCurrency(summary?.totalExpenses || 0)],
      ['Net Balance', formatCurrency(summary?.balance || 0)],
    ],
    headStyles: { fillColor: [99, 102, 241], textColor: 255 },
    bodyStyles: { fontSize: 11 },
    columnStyles: { 1: { halign: 'right', fontStyle: 'bold' } },
    styles: { cellPadding: 5 },
  });

  // Monthly trends table
  if (monthly && monthly.length > 0) {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30, 30, 30);
    doc.text('Monthly Trends', 14, doc.lastAutoTable.finalY + 14);

    autoTable(doc, {
      startY: doc.lastAutoTable.finalY + 18,
      head: [['Period', 'Income', 'Expenses', 'Net']],
      body: monthly.map(m => [
        m.name,
        formatCurrency(m.Income || 0),
        formatCurrency(m.Expenses || 0),
        formatCurrency((m.Income || 0) - (m.Expenses || 0))
      ]),
      headStyles: { fillColor: [99, 102, 241], textColor: 255 },
      alternateRowStyles: { fillColor: [248, 249, 255] },
      columnStyles: {
        1: { halign: 'right' },
        2: { halign: 'right' },
        3: { halign: 'right', fontStyle: 'bold' }
      },
      styles: { fontSize: 9, cellPadding: 4 },
    });
  }

  drawFooters(doc);
  doc.save(`monthly-summary-${monthName}-${year}.pdf`);
};
